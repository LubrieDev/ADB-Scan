//! Security audit without root.
//!
//! A single read-only script collects properties and settings; the evaluation
//! is pure and covered by tests. Nothing it does modifies the phone.

use crate::{i18n::{tr, trc}, t};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

use crate::parsers;

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum Severity {
    Ok,
    Info,
    Low,
    Medium,
    High,
}

impl Severity {
    pub fn label(self) -> &'static str {
        match self {
            Self::Ok => trc("status", "OK"),
            Self::Info => tr("Information"),
            Self::Low => tr("Low"),
            Self::Medium => tr("Medium"),
            Self::High => tr("High"),
        }
    }
    fn penalty(self) -> i64 {
        match self {
            Self::High => 15,
            Self::Medium => 7,
            Self::Low => 3,
            _ => 0,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Finding {
    pub id: String,
    pub category: String,
    pub title: String,
    pub severity: Severity,
    pub detail: String,
    pub recommendation: String,
    /// Affected packages (to show their names and act on them).
    #[serde(default)]
    pub packages: Vec<String>,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct Report {
    pub serial: String,
    pub model: String,
    pub android: String,
    pub patch: String,
    pub timestamp: i64,
    pub score: i64,
    pub findings: Vec<Finding>,
}

impl Report {
    pub fn count(&self, s: Severity) -> usize {
        self.findings.iter().filter(|f| f.severity == s).count()
    }

    pub fn grade(&self) -> &'static str {
        match self.score {
            90..=100 => tr("Excellent"),
            75..=89 => tr("Good"),
            55..=74 => tr("Could be better"),
            _ => tr("Poor"),
        }
    }

    /// Markdown report to share.
    pub fn to_markdown(&self) -> String {
        let mut s = t!("# Security audit — {}\n\n- Device: {} ({})\n- {}\n- Security patch: {}\n- Score: **{} / 100** ({})\n\n", self.model, self.model, self.serial, self.android, self.patch, self.score, self.grade());
        let mut sorted = self.findings.clone();
        sorted.sort_by_key(|f| std::cmp::Reverse(f.severity));
        for f in sorted {
            s.push_str(&format!("## [{}] {}\n\n{}\n\n", f.severity.label(), f.title, f.detail));
            if !f.recommendation.is_empty() {
                s.push_str(&t!("**Recommendation:** {}\n\n", f.recommendation));
            }
        }
        s.push_str(tr("---\nGenerated by ADB Scan (local analysis, without root, read-only).\n"));
        s
    }
}

